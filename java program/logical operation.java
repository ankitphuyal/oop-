public class Main {
    public static void main(String[] args) {

        boolean x = true;
        boolean y = false;

        System.out.println("\n logical operation");

        // Logical AND
        System.out.println("x && y = " + (x && y));

        // Logical OR
        System.out.println("x || y = " + (x || y));

        // Logical NOT
        System.out.println("!x = " + (!x));
        System.out.println("!y = " + (!y));
    }
}